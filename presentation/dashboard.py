@st.cache_data(ttl=3600)
def q_rfm(filters: FilterState) -> pd.DataFrame:
    fo = _filtered_orders(filters)
    fo = fo[fo["order_status"].isin(["delivered", "shipped", "invoiced"])]
    fi = ORDER_ITEMS[["order_id", "price"]]
    merged = fo.merge(fi, on="order_id", how="inner")

    if merged.empty:
        return pd.DataFrame(columns=["segment", "customers"])

    max_date = merged["order_purchase_timestamp"].dt.date.max()

    cust = (
        merged.groupby("customer_unique_id")
        .agg(
            last_order=("order_purchase_timestamp", "max"),
            frequency=("order_id",  "nunique"),
            monetary=("price", "sum"),
        )
        .reset_index()
    )
    cust["recency"] = (max_date - cust["last_order"].dt.date).apply(lambda d: d.days)

    def _segment(row) -> str:
        r, f, m = row["recency"], row["frequency"], row["monetary"]
        if r <= 90  and f >= 3 and m >= 300: return "Champions"
        if r <= 180 and f >= 2:              return "Loyal"
        if r <= 90:                          return "Promising"
        if r <= 365:                         return "At Risk"
        return "Inactive"

    cust["segment"] = cust.apply(_segment, axis=1)
    return (
        cust.groupby("segment")["customer_unique_id"]
        .count()
        .reset_index(name="customers")
        .sort_values("customers", ascending=False)
    )


