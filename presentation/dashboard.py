@st.cache_data(ttl=3600)
def q_monthly_revenue(filters: FilterState) -> pd.DataFrame:
    fo = _filtered_orders(filters)
    fo = fo[~fo["order_status"].isin(["canceled", "unavailable"])]
    fi = ORDER_ITEMS[["order_id", "price", "freight_value"]]
    merged = fo.merge(fi, on="order_id", how="inner")
    merged["revenue"] = merged["price"] + merged["freight_value"]
    merged["month"]   = merged["order_purchase_timestamp"].dt.to_period("M").astype(str)

    return (
        merged.groupby("month")
        .agg(revenue=("revenue", "sum"), orders=("order_id", "nunique"))
        .reset_index()
        .sort_values("month")
    )


