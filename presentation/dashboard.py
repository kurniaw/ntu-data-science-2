@st.cache_data(ttl=3600)
def q_overview_kpis(filters: FilterState) -> pd.DataFrame:
    fo = _filtered_orders(filters)
    fi = ORDER_ITEMS[["order_id", "price", "freight_value"]]
    merged = fo.merge(fi, on="order_id", how="inner")
    merged["item_value"] = merged["price"] + merged["freight_value"]

    order_vals  = merged.groupby("order_id")["item_value"].sum()
    gmv         = order_vals.sum()
    total_orders = len(order_vals)
    aov         = order_vals.mean()

    delivered = fo[
        (fo["order_status"] == "delivered") & fo["order_delivered_customer_date"].notna()
    ]
    if delivered.empty:
        avg_days = float("nan")
        on_time_rate = float("nan")
    else:
        avg_days = (
            delivered["order_delivered_customer_date"] - delivered["order_purchase_timestamp"]
        ).dt.days.mean()
        on_time_rate = (
            delivered["order_delivered_customer_date"] <= delivered["order_estimated_delivery_date"]
        ).mean()

    return pd.DataFrame([{
        "gmv": gmv, "total_orders": total_orders, "aov": aov,
        "delivered": len(delivered), "avg_days": avg_days, "on_time_rate": on_time_rate,
    }])


