@st.cache_data(ttl=3600)
def q_sentiment_by_category(filters: FilterState) -> pd.DataFrame:
    r = REVIEWS[REVIEWS["review_score"].notna()].copy()

    # Join with orders to get timestamp for date filter
    order_ts = ORDERS[["order_id", "order_purchase_timestamp"]].rename(columns={"order_id": "order_key"})
    r = r.merge(order_ts, on="order_key", how="inner")

    if filters.date_from:
        r = r[r["order_purchase_timestamp"].dt.date >= filters.date_from]
    if filters.date_to:
        r = r[r["order_purchase_timestamp"].dt.date <= filters.date_to]

    # Join with products and categories for category filter
    cat_curr = PRODUCT_CATEGORIES[PRODUCT_CATEGORIES["is_current"]][
        ["category_name", "category_name_english", "category_type"]
    ]
    prod_cat = PRODUCTS[["product_id", "product_category_name"]].merge(
        cat_curr, left_on="product_category_name", right_on="category_name", how="left"
    )
    r = r.merge(prod_cat, left_on="product_key", right_on="product_id", how="left")

    if filters.categories:
        r = r[r["category_name_english"].isin(filters.categories)]

    r["category_type"] = r["category_type"].fillna("Other")

    agg = (
        r.groupby("category_type")
        .agg(
            positive_rate=("review_sentiment", lambda x: (x == "positive").mean()),
            avg_score=("review_score", "mean"),
            cnt=("review_id", "count"),
        )
        .reset_index()
    )
    return (
        agg[agg["cnt"] >= 10]
        .sort_values("positive_rate", ascending=False)
    )


