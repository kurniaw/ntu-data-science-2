@st.cache_data(ttl=3600)
def q_order_frequency(filters: FilterState) -> pd.DataFrame:
    fo = _filtered_orders(filters)
    cust_counts = fo.groupby("customer_unique_id")["order_id"].nunique()

    def _bucket(n: int) -> str:
        if n == 1: return "1 order"
        if n == 2: return "2 orders"
        if n == 3: return "3 orders"
        return "4+ orders"

    buckets = cust_counts.map(_bucket).value_counts().reset_index()
    buckets.columns = ["bucket", "customers"]
    return buckets.sort_values("bucket")


@st.cache_data(ttl=3600)
def q_delivery_by_state(filters: FilterState) -> pd.DataFrame:
    fo = _filtered_orders(filters)
    fo = fo[
        (fo["order_status"] == "delivered")
        & fo["order_delivered_customer_date"].notna()
        & fo["order_purchase_timestamp"].notna()
    ].copy()
    fo["delivery_days"] = (
        fo["order_delivered_customer_date"] - fo["order_purchase_timestamp"]
    ).dt.days
    fo["on_time"] = fo["order_delivered_customer_date"] <= fo["order_estimated_delivery_date"]

    agg = (
        fo.groupby("customer_state")
        .agg(
            avg_days=("delivery_days", "mean"),
            on_time_rate=("on_time", "mean"),
            orders=("order_id", "count"),
        )
        .reset_index()
        .rename(columns={"customer_state": "state"})
    )
    return agg[agg["orders"] >= 10].sort_values("avg_days")


