# ── Filter helper ─────────────────────────────────────────────────────────────
def _filtered_orders(
    filters: FilterState,
    *,
    apply_states: bool = True,
    apply_regions: bool = True,
    apply_categories: bool = True,
) -> pd.DataFrame:
    """Return a filtered slice of fct_orders based on FilterState."""
    df = ORDERS
    if filters.date_from:
        df = df[df["order_purchase_timestamp"].dt.date >= filters.date_from]
    if filters.date_to:
        df = df[df["order_purchase_timestamp"].dt.date <= filters.date_to]
    if apply_states and filters.states:
        df = df[df["customer_state"].isin(filters.states)]
    if apply_regions and filters.regions:
        df = df[df["region"].isin(filters.regions)]
    if apply_categories and filters.categories:
        qualifying = set(
            ORDER_ITEMS.loc[
                ORDER_ITEMS["category_name_english"].isin(filters.categories),
                "order_id",
            ].unique()
        )
        df = df[df["order_id"].isin(qualifying)]
    return df


