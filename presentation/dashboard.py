@st.cache_data(ttl=3600)
def q_customer_order_map(filters: FilterState) -> pd.DataFrame:
    fo = _filtered_orders(filters)
    fi = ORDER_ITEMS[["order_id", "price"]]
    merged = fo.merge(fi, on="order_id", how="inner")
    merged = merged.merge(
        GEO[["zip_code_prefix", "latitude", "longitude", "city"]],
        left_on="customer_zip_code", right_on="zip_code_prefix", how="inner",
    )
    merged = merged.dropna(subset=["latitude", "longitude"])

    result = (
        merged.groupby(["latitude", "longitude", "city", "customer_state", "region"])
        .agg(orders=("order_id", "nunique"), revenue=("price", "sum"))
        .reset_index()
        .rename(columns={"latitude": "lat", "longitude": "lng", "customer_state": "state"})
    )
    return result


@st.cache_data(ttl=3600)
def q_seller_map(filters: FilterState) -> pd.DataFrame:
    sellers_geo = SELLERS.merge(
        GEO[["zip_code_prefix", "latitude", "longitude", "city", "state", "region"]],
        left_on="seller_zip_code", right_on="zip_code_prefix", how="inner",
    ).dropna(subset=["latitude", "longitude"])

    if filters.regions:
        sellers_geo = sellers_geo[sellers_geo["region"].isin(filters.regions)]

    return (
        sellers_geo.groupby(["latitude", "longitude", "city", "state", "region"])
        .agg(seller_count=("seller_id", "nunique"))
        .reset_index()
        .rename(columns={"latitude": "lat", "longitude": "lng"})
    )


@st.cache_data(ttl=3600)
def q_regional_performance(filters: FilterState) -> pd.DataFrame:
    # Only date + region filters (no state/category) — mirrors original BQ query
    fo = ORDERS[ORDERS["order_delivered_customer_date"].notna()].copy()

    if filters.date_from:
        fo = fo[fo["order_purchase_timestamp"].dt.date >= filters.date_from]
    if filters.date_to:
        fo = fo[fo["order_purchase_timestamp"].dt.date <= filters.date_to]
    if filters.regions:
        fo = fo[fo["region"].isin(filters.regions)]

    fi = ORDER_ITEMS[["order_id", "price"]]
    merged = fo.merge(fi, on="order_id", how="inner")

    merged["delivery_days"] = (
        merged["order_delivered_customer_date"] - merged["order_purchase_timestamp"]
    ).dt.days

    return (
        merged.groupby("region")
        .agg(
            orders=("order_id", "nunique"),
            revenue=("price", "sum"),
            avg_delivery_days=("delivery_days", "mean"),
        )
        .reset_index()
        .sort_values("revenue", ascending=False)
    )


